Category categoryFromTable(char32_t codePoint)
{
    const auto key = (static_cast<std::uint32_t>(codePoint) << 2) | categoryBits;

    const auto* found = std::upper_bound(std::begin(unicodeCategoryTransitions),
                                         std::end(unicodeCategoryTransitions),
                                         key);

    if (found == std::begin(unicodeCategoryTransitions))
        return Category::other;

    return static_cast<Category>(*(found - 1) & categoryBits);
}

Category asciiCategory(char32_t codePoint)
{
    if ((codePoint >= 0x09 && codePoint <= 0x0D) || codePoint == 0x20)
        return Category::whitespace;

    if ((codePoint >= U'a' && codePoint <= U'z')
        || (codePoint >= U'A' && codePoint <= U'Z'))
        return Category::letter;

    if (codePoint >= U'0' && codePoint <= U'9')
        return Category::number;

    return Category::other;
}

// The Unicode White_Space property above U+007F. Notably not U+200B, U+FEFF
// or U+180E, none of which carry it.
bool isWhitespaceAboveAscii(char32_t codePoint)
{
    return codePoint == 0x85 || codePoint == 0xA0 || codePoint == 0x1680
           || (codePoint >= 0x2000 && codePoint <= 0x200A) || codePoint == 0x2028
           || codePoint == 0x2029 || codePoint == 0x202F || codePoint == 0x205F
           || codePoint == 0x3000;
}

int continuationBytesFor(unsigned char leadingByte)
{
    if (leadingByte < 0x80)
        return 0;

    if ((leadingByte & 0xE0) == 0xC0)
        return 1;

    if ((leadingByte & 0xF0) == 0xE0)
        return 2;

    if ((leadingByte & 0xF8) == 0xF0)
        return 3;

    return -1;
}

bool isOverlongOrOutOfRange(char32_t value, int continuationBytes)
{
    if (value > 0x10FFFF || (value >= 0xD800 && value <= 0xDFFF))
        return true;

    if (continuationBytes == 1)
        return value < 0x80;

    if (continuationBytes == 2)
        return value < 0x800;

    return value < 0x10000;
}
