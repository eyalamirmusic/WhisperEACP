Category categoryOf(char32_t codePoint)
{
    if (codePoint < 0x80)
        return asciiCategory(codePoint);

    if (isWhitespaceAboveAscii(codePoint))
        return Category::whitespace;

    return categoryFromTable(codePoint);
}

CodePoint readCodePoint(std::string_view text, std::size_t position)
{
    const auto leadingByte = static_cast<unsigned char>(text[position]);
    const auto asSingleByte =
        CodePoint {static_cast<char32_t>(leadingByte), 1, Category::other};

    const auto continuationBytes = continuationBytesFor(leadingByte);

    if (continuationBytes < 0)
        return asSingleByte;

    if (continuationBytes == 0)
        return {static_cast<char32_t>(leadingByte), 1, asciiCategory(leadingByte)};

    if (position + static_cast<std::size_t>(continuationBytes) >= text.size())
        return asSingleByte;

    auto value = static_cast<char32_t>(leadingByte & (0x3F >> continuationBytes));

    for (auto i = 1; i <= continuationBytes; ++i)
    {
        const auto next =
            static_cast<unsigned char>(text[position + std::size_t(i)]);

        if ((next & 0xC0) != 0x80)
            return asSingleByte;

        value = (value << 6) | static_cast<char32_t>(next & 0x3F);
    }

    if (isOverlongOrOutOfRange(value, continuationBytes))
        return asSingleByte;

    return {value, continuationBytes + 1, categoryOf(value)};
}

void appendUtf8(std::string& text, char32_t codePoint)
{
    const auto byteAt = [&](char32_t shift, char32_t marker)
    { return static_cast<char>(marker | ((codePoint >> shift) & 0x3F)); };

    if (codePoint < 0x80)
    {
        text += static_cast<char>(codePoint);
    }
    else if (codePoint < 0x800)
    {
        text += static_cast<char>(0xC0 | (codePoint >> 6));
        text += byteAt(0, 0x80);
    }
    else if (codePoint < 0x10000)
    {
        text += static_cast<char>(0xE0 | (codePoint >> 12));
        text += byteAt(6, 0x80);
        text += byteAt(0, 0x80);
    }
    else
    {
        text += static_cast<char>(0xF0 | (codePoint >> 18));
        text += byteAt(12, 0x80);
        text += byteAt(6, 0x80);
        text += byteAt(0, 0x80);
    }
}
